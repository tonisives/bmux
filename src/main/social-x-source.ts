// X extraction adapted from the existing TweetTrace extension.
export let socialXSource = [
  "(() => {// Track last-sent engagement counts per URL so we re-emit only on change.",
  "const lastSentCounts = new Map();",
  "",
  "function parseTweetUrl(href) {",
  "    if (!href) return null;",
  "    const match = href.match(/^\\/([^\\/]+)\\/status\\/(\\d+)/);",
  "    if (!match) return null;",
  "    return {",
  "        handle: match[1],",
  "        tweetId: match[2],",
  "        url: `https://x.com/${match[1]}/status/${match[2]}`,",
  "    };",
  "}",
  "",
  "function extractTextFromTweetTextNode(node) {",
  "    if (!node) return \"\";",
  "    const parts = [];",
  "    node.childNodes.forEach((n) => {",
  "        if (n.nodeType === Node.TEXT_NODE) {",
  "            parts.push(n.textContent);",
  "        } else if (n.nodeType === Node.ELEMENT_NODE && (n.tagName === \"SPAN\" || n.tagName === \"A\")) {",
  "            parts.push(n.textContent);",
  "        } else if (n.nodeType === Node.ELEMENT_NODE && n.tagName === \"IMG\" && n.alt) {",
  "            parts.push(n.alt);",
  "        }",
  "    });",
  "    return parts.join(\"\").trim();",
  "}",
  "",
  "function extractAuthorName(scope) {",
  "    try {",
  "        const userNameEl = scope.querySelector('[data-testid=\"User-Name\"]');",
  "        if (!userNameEl) return null;",
  "        const nameEl = userNameEl.querySelector('div[dir=\"ltr\"] > span > span');",
  "        return nameEl ? nameEl.textContent.trim() : null;",
  "    } catch {",
  "        return null;",
  "    }",
  "}",
  "",
  "function extractTweetTime(scope) {",
  "    try {",
  "        const timeEl = scope.querySelector(\"time\");",
  "        return timeEl ? timeEl.getAttribute(\"datetime\") : null;",
  "    } catch {",
  "        return null;",
  "    }",
  "}",
  "",
  "function extractAvatarUrl(scope) {",
  "    try {",
  "        const imgEl = scope.querySelector('[data-testid=\"Tweet-User-Avatar\"] img');",
  "        return imgEl ? imgEl.src : null;",
  "    } catch {",
  "        return null;",
  "    }",
  "}",
  "",
  "// Pulls the first integer out of a string like \"12 replies. Reply\" or \"1,234 Likes\".",
  "// Also handles \"1.2K\", \"3.4M\" suffix forms that appear in button text.",
  "function parseCountFromText(s) {",
  "    if (!s) return 0;",
  "    const cleaned = s.replace(/,/g, \"\");",
  "    const suffix = cleaned.match(/([\\d.]+)\\s*([KMB])/i);",
  "    if (suffix) {",
  "        const n = parseFloat(suffix[1]);",
  "        const mult = { K: 1e3, M: 1e6, B: 1e9 }[suffix[2].toUpperCase()] || 1;",
  "        return Math.round(n * mult);",
  "    }",
  "    const plain = cleaned.match(/\\d+/);",
  "    return plain ? parseInt(plain[0], 10) : 0;",
  "}",
  "",
  "function extractCountByTestId(scope, testId) {",
  "    const el = scope.querySelector(`[data-testid=\"${testId}\"]`);",
  "    if (!el) return 0;",
  "    // aria-label holds the full count (\"1234 replies\"), button text may be truncated (\"1.2K\").",
  "    const label = el.getAttribute(\"aria-label\") || el.textContent || \"\";",
  "    return parseCountFromText(label);",
  "}",
  "",
  "function extractViews(scope) {",
  "    // View count sits in an anchor whose href ends with /analytics.",
  "    const analyticsLink = scope.querySelector('a[href$=\"/analytics\"]');",
  "    if (!analyticsLink) return 0;",
  "    const label = analyticsLink.getAttribute(\"aria-label\") || analyticsLink.textContent || \"\";",
  "    return parseCountFromText(label);",
  "}",
  "",
  "function extractEngagement(scope) {",
  "    return {",
  "        replies: extractCountByTestId(scope, \"reply\"),",
  "        retweets: extractCountByTestId(scope, \"retweet\"),",
  "        likes: extractCountByTestId(scope, \"like\"),",
  "        views: extractViews(scope),",
  "    };",
  "}",
  "",
  "function findStatusLink(scope) {",
  "    const anchors = scope.querySelectorAll('a[href*=\"/status/\"]');",
  "    for (const a of anchors) {",
  "        const parsed = parseTweetUrl(a.getAttribute(\"href\"));",
  "        if (parsed) return parsed;",
  "    }",
  "    return null;",
  "}",
  "",
  "function isRetweet(tweetEl) {",
  "    const ctx = tweetEl.querySelector('[data-testid=\"socialContext\"]');",
  "    if (!ctx) return false;",
  "    const txt = (ctx.textContent || \"\").toLowerCase();",
  "    return txt.includes(\"reposted\") || txt.includes(\"retweeted\");",
  "}",
  "",
  "function findQuotedTweetNode(tweetEl) {",
  "    const candidates = tweetEl.querySelectorAll('div[role=\"link\"][tabindex=\"0\"]');",
  "    for (const c of candidates) {",
  "        const hasText = c.querySelector('[data-testid=\"tweetText\"]');",
  "        const hasTime = c.querySelector(\"time\");",
  "        if (hasText && hasTime) return c;",
  "    }",
  "    return null;",
  "}",
  "",
  "// Detect whether this tweet is a reply. X renders a \"Replying to @handle\" row",
  "// above the tweetText; it's not inside a quoted-tweet node and sits before the",
  "// outer text. We locate it, then pull the first /handle[/status/ID] anchor in",
  "// that row as the parent.",
  "function extractReplyContext(tweetEl, outerTextEl, quotedNode) {",
  "    // Find a candidate row whose textContent starts with \"Replying to\".",
  "    const candidates = tweetEl.querySelectorAll(\"div\");",
  "    let replyingRow = null;",
  "    for (const el of candidates) {",
  "        if (quotedNode && quotedNode.contains(el)) continue;",
  "        // Skip the outer text node itself.",
  "        if (el.contains(outerTextEl) && el !== tweetEl) {",
  "            // A container that wraps the outer text is fine to scan; we just",
  "            // need the specific \"Replying to\" leaf, handled by startsWith below.",
  "        }",
  "        const txt = (el.textContent || \"\").trim();",
  "        if (!txt) continue;",
  "        if (!/^replying to\\b/i.test(txt)) continue;",
  "        // Prefer the tightest match: skip ancestors that also match by taking",
  "        // the deepest element whose direct text starts with \"Replying to\".",
  "        if (replyingRow && replyingRow.contains(el)) {",
  "            replyingRow = el;",
  "        } else if (!replyingRow) {",
  "            replyingRow = el;",
  "        }",
  "    }",
  "    if (!replyingRow) return { isReply: false, inReplyToUrl: null, inReplyToHandle: null };",
  "",
  "    // First @handle link inside the row.",
  "    const handleAnchor = replyingRow.querySelector('a[href^=\"/\"]');",
  "    if (!handleAnchor) return { isReply: true, inReplyToUrl: null, inReplyToHandle: null };",
  "    const href = handleAnchor.getAttribute(\"href\") || \"\";",
  "    // href may be \"/handle\" (parent user) or \"/handle/status/ID\" (parent tweet).",
  "    const statusMatch = href.match(/^\\/([^\\/]+)\\/status\\/(\\d+)/);",
  "    if (statusMatch) {",
  "        return {",
  "            isReply: true,",
  "            inReplyToUrl: `https://x.com/${statusMatch[1]}/status/${statusMatch[2]}`,",
  "            inReplyToHandle: statusMatch[1],",
  "        };",
  "    }",
  "    const handleMatch = href.match(/^\\/([^\\/?#]+)/);",
  "    return {",
  "        isReply: true,",
  "        inReplyToUrl: null,",
  "        inReplyToHandle: handleMatch ? handleMatch[1] : null,",
  "    };",
  "}",
  "",
  "function buildRecord({ textEl, scope, isQuote, quotedUrl, isRetweetFlag, retweetOfUrl, engagement, replyContext }) {",
  "    const tweetText = extractTextFromTweetTextNode(textEl);",
  "    if (!tweetText) return null;",
  "",
  "    const linkInfo = findStatusLink(scope);",
  "    if (!linkInfo) return null;",
  "",
  "    return {",
  "        tweet_id: linkInfo.tweetId,",
  "        handle: linkInfo.handle,",
  "        author_name: extractAuthorName(scope),",
  "        url: linkInfo.url,",
  "        text: tweetText,",
  "        posted_at: extractTweetTime(scope),",
  "        avatar_url: extractAvatarUrl(scope),",
  "        is_retweet: !!isRetweetFlag,",
  "        retweet_of_url: retweetOfUrl || null,",
  "        is_quote: !!isQuote,",
  "        quoted_url: quotedUrl || null,",
  "        is_reply: !!replyContext?.isReply,",
  "        in_reply_to_url: replyContext?.inReplyToUrl || null,",
  "        in_reply_to_handle: replyContext?.inReplyToHandle || null,",
  "        likes: engagement?.likes ?? 0,",
  "        retweets: engagement?.retweets ?? 0,",
  "        replies: engagement?.replies ?? 0,",
  "        views: engagement?.views ?? 0,",
  "    };",
  "}",
  "",
  "function engagementSignature(r) {",
  "    return `${r.likes}|${r.retweets}|${r.replies}|${r.views}`;",
  "}",
  "",
  "function shouldEmit(record) {",
  "    const sig = engagementSignature(record);",
  "    const prev = lastSentCounts.get(record.url);",
  "    if (prev === sig) return false;",
  "    lastSentCounts.set(record.url, sig);",
  "    return true;",
  "}",
  "",
  "function extractTweetData() {",
  "    const batch = [];",
  "    const tweetElements = document.querySelectorAll('[data-testid=\"tweet\"]');",
  "",
  "    tweetElements.forEach((tweetEl) => {",
  "        const quotedNode = findQuotedTweetNode(tweetEl);",
  "        let quotedRecord = null;",
  "",
  "        if (quotedNode) {",
  "            const innerTextEl = quotedNode.querySelector('[data-testid=\"tweetText\"]');",
  "            if (innerTextEl) {",
  "                // Quoted tweets don't carry their own action bar in the preview \u2014 leave counts at 0.",
  "                quotedRecord = buildRecord({",
  "                    textEl: innerTextEl,",
  "                    scope: quotedNode,",
  "                    isQuote: false,",
  "                    quotedUrl: null,",
  "                    isRetweetFlag: false,",
  "                    retweetOfUrl: null,",
  "                    engagement: { likes: 0, retweets: 0, replies: 0, views: 0 },",
  "                    replyContext: null,",
  "                });",
  "            }",
  "        }",
  "",
  "        let outerTextEl = null;",
  "        const allTextEls = tweetEl.querySelectorAll('[data-testid=\"tweetText\"]');",
  "        for (const el of allTextEls) {",
  "            if (!quotedNode || !quotedNode.contains(el)) {",
  "                outerTextEl = el;",
  "                break;",
  "            }",
  "        }",
  "        if (!outerTextEl) return;",
  "",
  "        const retweetFlag = isRetweet(tweetEl);",
  "        const outerRecord = buildRecord({",
  "            textEl: outerTextEl,",
  "            scope: tweetEl,",
  "            isQuote: !!quotedRecord,",
  "            quotedUrl: quotedRecord ? quotedRecord.url : null,",
  "            isRetweetFlag: retweetFlag,",
  "            retweetOfUrl: retweetFlag ? (findStatusLink(tweetEl)?.url || null) : null,",
  "            engagement: extractEngagement(tweetEl),",
  "            replyContext: extractReplyContext(tweetEl, outerTextEl, quotedNode),",
  "        });",
  "",
  "        if (outerRecord && shouldEmit(outerRecord)) {",
  "            batch.push(outerRecord);",
  "        }",
  "        if (quotedRecord && shouldEmit(quotedRecord)) {",
  "            batch.push(quotedRecord);",
  "        }",
  "    });",
  "",
  "    if (batch.length > 0) {",
  "        return batch;",
  "    }",
  "}",
  "",
  ";return extractTweetData() || []})()",
].join('\n')
